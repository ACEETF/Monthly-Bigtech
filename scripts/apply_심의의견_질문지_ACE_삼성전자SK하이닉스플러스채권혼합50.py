def para_text(p):
    return "".join(r.text for r in p.runs)


def set_para_text(p, text):
    """첫 run의 서식을 유지한 채 문단 텍스트를 교체."""
    runs = p.runs
    runs[0].text = text
    for r in runs[1:]:
        r._element.getparent().remove(r._element)


def iter_paragraphs(doc):
    for p in doc.paragraphs:
        yield p
    for t in doc.tables:
        for row in t.rows:
            for c in row.cells:
                for p in c.paragraphs:
                    yield p


def main():
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    doc = Document(os.path.join(base, SRC))
    paras = list(iter_paragraphs(doc))

    for old, new, why in EDITS:
        hits = [p for p in paras if old in para_text(p)]
        assert len(hits) == 1, f"[{len(hits)}건] 치환 대상 불일치: {old[:40]}... ({why})"
        p = hits[0]
        set_para_text(p, para_text(p).replace(old, new))

    full = "\n".join(para_text(p) for p in paras)
    for word in BANNED:
        for line in full.split("\n"):
            if word in line and not any(a in line for a in ALLOWED_CONTEXT):
                raise AssertionError(f"제한 표현 '{word}' 잔존: {line[:60]}")

    out = os.path.join(base, DST)
    doc.save(out)

    # 소보부 재제출용 수정대비표
    lines = ["# [ETF 아는형] ACE 삼성전자SK하이닉스플러스채권혼합50 질문지 스크립트",
             "## 소비자보호부 심의의견(2026-08-18) 반영 내역",
             "",
             f"- 원본: `{SRC}`",
             f"- 반영본: `{DST}`",
             f"- 반영 건수: {len(EDITS)}건",
             "",
             "| # | 심의 근거 | 수정 전 | 수정 후 |",
             "|---|---|---|---|"]
    for i, (old_t, new_t, why) in enumerate(EDITS, 1):
        e = lambda t: t.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {i} | {e(why)} | {e(old_t)} | {e(new_t)} |")
    md = os.path.join(base, MEMO)
    with open(md, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print("저장:", out)
    print("저장:", md)
    print(f"반영 건수: {len(EDITS)}건")


if __name__ == "__main__":
    main()
